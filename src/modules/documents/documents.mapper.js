export const toPublicDocument = (document) => ({
  id: document.id,
  filename: document.filename,
  displayName: document.displayName ?? document.filename,
  folder: document.folder ?? null,
  tags: document.tags ?? [],
  mimeType: document.mimeType,
  sizeBytes: document.sizeBytes,
  status: document.status,
  errorMessage: document.errorMessage ?? null,
  processingStep: document.processingStep ?? null,
  progress: document.progress ?? 0,
  attemptCount: document.attemptCount ?? 0,
  pageCount: document.pageCount ?? null,
  wordCount: document.wordCount ?? null,
  charCount: document.charCount ?? null,
  createdAt: document.createdAt,
});
